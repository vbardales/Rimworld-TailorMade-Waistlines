// node gen-wardrobe.js : writes 08-wardrobe.feature from the setup of 05-gallery.feature.
// One scenario per clothing mod: the ten bodies of the gallery, first bare, then dressed in each listed garment.
// The two children are left bare in the dressed outfits: adult garments are refused on a child ("M-Kid should wear ...; it wears nothing").
// LEWD Hooman Apparel ships Male and Female textures only: on Thin, Fat and Hulk it logs "Failed to find any textures at ...TubeTop_Thin" (run f8f0), so it is worn on the two average bodies.
const fs = require('fs');
const gallery = fs.readFileSync(__dirname + '/05-gallery.feature', 'utf8').replace(/\r\n/g, '\n').split('\n');
const start = gallery.findIndex(l => /the animals are removed from the sanctuary/.test(l));
const end = gallery.findIndex(l => /^\s*When I destroy the gear of "M-Thin"/.test(l));
const setup = gallery.slice(start, end);
const bodies = ['M-Thin', 'M-Avg', 'M-Fat', 'M-Hulk', 'M-Kid', 'F-Thin', 'F-Avg', 'F-Fat', 'F-Hulk', 'F-Kid'];
const refit = process.argv[2] === 'refit';
const wardrobeMods = [
  { id: 'UNAGI.Ap.Dress', ws: '3352990362', name: 'UNAGI Royalty Apparel', garments: ['Apparel_UNARoyalDress', 'Apparel_UNA_dressR', 'Apparel_UNA_gothicdress', 'UNA_MstyleShirtpants'] },
  { id: 'UNAGI.Battle.coat', ws: '3301577366', name: 'UNAGI Battle Coat', pants: true, garments: ['UNA_MaidBattleArmor', 'UNA_FlakDress', 'UNA_PlateDress'] },
  { id: 'UNAGI.huyuhuku.SET', ws: '3266399912', name: 'UNAGI Winter clothing', pants: true, garments: ['UNAGIapaka', 'UNAGImohukepu'] },
  { id: 'UNAGI.suit.SET', ws: '3253298952', name: 'UNAGI SimpleSuit', garments: ['UNAGInoEshirt', 'UNAGInoSDs'] },
  { id: 'UNAGI.Wahuu.hako', ws: '3297676809', name: 'UNAGI Japanese Assortment', garments: ['UNAwasitagi', 'Apparel_UNAwahaori', 'UNAkariginu'] },
  { id: 'UNAGI.Cafe.gohan', ws: '3325530853', name: 'UNAGI CAFE', garments: ['UNAcafe_wanpi', 'Apparel_UNAcafe_epuron'] },
  { id: 'GilieART.LewdHoomanApparel', ws: '3275648920', name: 'LEWD Hooman Apparel', noKids: true, only: ['M-Avg', 'F-Avg'], garments: ['LEWD_Apparel_MicroSkirt', 'LEWD_Apparel_TubeTop', 'LEWD_Apparel_FlakiniVest'] },
  { id: 'BBIS.MaidProject', ws: '1498756997', name: 'Maid Project', garments: ['ChefMaid', 'CleanerMaid', 'FightMaid', 'NurseMaid'] },
];
// 'refit': vanilla garments that WDI draws nothing for, on the ten bodies; compared with and without TailorMade.
const refitMods = [{ id: null, name: 'Vanilla garments without WDI art', pants: true, garments: ['Apparel_Jacket', 'Apparel_Parka', 'Apparel_Duster', 'Apparel_FlakVest'] }];
const mods = refit ? refitMods : wardrobeMods;
const o = [];
o.push('# Wardrobe: clothing libraries on the ten bodies of the gallery, bare then dressed, one scenario per mod. Generated by gen-wardrobe.js; do not edit by hand.');
o.push('# Every image is opened and read: the question is whether the garment looks right on the body, with and without this mod\'s cut.');
o.push('# Pass: wsl-deps.wardrobe.map.');
o.push((refit ? '@review @refit @timeout:300' : '@review @wardrobe @timeout:300'), 'Feature: clothing libraries on the ten bodies', '', '  Background:', '    Given the save "Nelims-tribe" is loaded', '');
for (const m of mods) {
  o.push('  @requires:wdi.realistic.bodies @requires:nelim.pickletools.screenshotstudio @requires:nelim.pickletools.colonistrace' + (m.id ? ' @requires:' + m.id : '') + (m.noKids ? '' : ' @requires:LoneKin.ChildrenWearAnything'));
  o.push('  Scenario: ' + m.name + ' on ten bodies');
  setup.forEach((l, i) => o.push(i === 0 ? l.replace(/^\s*Given/, '    Given') : l));
  const shot = (label, first) => {
    o.push('    And Nelim\'s Sanctuary: I am at the sanctuary "calm-zone-close"');
    if (first) o.push('    And Nelim\'s Pickle Tools: studio presentation mode is enabled');
    o.push('    And I wait 90 ticks', '    And I take a screenshot "' + (refit ? 'refit' : 'wardrobe') + ', ' + m.name.toLowerCase() + ', ' + label + '"');
  };
  bodies.forEach((b, i) => o.push((i === 0 ? '    When' : '    And') + ' I destroy the gear of "' + b + '"'));
  shot('bare', true);
  for (const g of m.garments) {
    // The two children stay bare: an adult garment is refused on a child ("M-Kid should wear ...; it wears nothing").
    for (const b of bodies) {
      o.push('    And I destroy the gear of "' + b + '"');
      // Children wear the garments through "Children Wear Anything"; never the LEWD ones (micro skirt, tube top, flakini).
      if ((!/Kid/.test(b) || !m.noKids) && (!m.only || m.only.includes(b))) {
        // Coats and capes hang over trousers: the legless body shows the waist otherwise.
        if (m.pants) o.push('    And Nelim\'s Pickle Tools: "' + b + '" wears "Apparel_Pants"');
        o.push('    And Nelim\'s Pickle Tools: "' + b + '" wears "' + g + '"');
      }
    }
    shot(g, false);
  }
  o.push('');
}
fs.writeFileSync(__dirname + (refit ? '/09-refit.feature' : '/08-wardrobe.feature'), o.join('\n'));
console.log('wrote ' + (refit ? '09-refit' : '08-wardrobe') + '.feature, ' + mods.length + ' scenarios');
