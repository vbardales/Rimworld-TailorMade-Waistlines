'use strict';
// Writes the GIMP project that stacks every body retexture on top of each
// other, one layer per mod, so their silhouettes can be compared directly.
//
//   node make-gimp-bodies.js            # writes _tools/gimp-bodies.scm
//   node make-gimp-bodies.js --list     # just print what it found
//
// The sources come from _tools/body-mods.json, which holds the mods that ship
// a full set of human `Naked_*` textures. Race retextures are not in it: a
// scaly or furry body is a different shape by design and tells us nothing
// about whether a fix written for one human body fits another.
//
// There is no vanilla layer. RimWorld 1.6 ships no loose textures at all -
// Data/Core holds only About, Defs and Languages, everything else is inside
// the engine's asset bundles - so the vanilla body cannot be read from disk.
// The closest stand-in is a retexture that keeps the vanilla silhouette.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONFIG = path.join(__dirname, 'body-mods.json');
const OUT = path.join(__dirname, 'gimp-bodies.scm');

const BODIES = ['Female', 'Male', 'Thin', 'Thin_Female', 'Fat', 'Fat_Female',
    'Hulk', 'Hulk_Female', 'Child'];
const FACINGS = ['south', 'north', 'east'];

const mods = JSON.parse(fs.readFileSync(CONFIG, 'utf8'));

// Most mods name a body `Naked_<BodyType>_<facing>.png`. Sized Apparel slips
// an extra `_BaseBody` in the middle, and the Core stand-in is not a body at
// all but a garment, so the whole pattern is overridable.
const fileFor = (mod, body, facing) => mod.dir + '/' +
    (mod.pattern || 'Naked_{body}{suffix}_{facing}.png')
        .replace('{body}', body)
        .replace('{suffix}', mod.suffix || '')
        .replace('{facing}', facing);

// Only the combinations that actually exist get a layer; a mod that skipped a
// body type simply has one fewer.
const rows = [];
for (const body of BODIES) {
    for (const facing of FACINGS) {
        const layers = [];
        for (const mod of mods) {
            const file = fileFor(mod, body, facing);
            if (fs.existsSync(file)) layers.push({ label: mod.label, file });
        }
        if (layers.length) rows.push({ body, facing, layers });
    }
}

if (process.argv.includes('--list')) {
    for (const mod of mods) {
        const n = BODIES.flatMap(b => FACINGS.map(f => fileFor(mod, b, f)))
            .filter(f => fs.existsSync(f)).length;
        console.log(`${String(n).padStart(3)}  ${mod.label}`);
    }
    console.log(`\n${mods.length} mods, ${rows.length} of ${BODIES.length * FACINGS.length} slots covered`);
    return;
}

const esc = s => s.replace(/\\/g, '/').replace(/"/g, '\\"');

const out = [];
out.push('; Every human body retexture on disk, stacked for comparison.');
out.push(';');
out.push('; GENERATED by _tools/make-gimp-bodies.js - edit that, not this.');
out.push(';');
out.push('; In GIMP: Filters > Script-Fu > Console, then');
out.push(';');
out.push(`;   (load "${esc(OUT)}")`);
out.push(';   (tb-open "Female" "south")    ; one body type, one facing');
out.push(';   (tb-open-body "Female")       ; its three facings');
out.push(';');
out.push('; One layer per mod, the first visible and the rest hidden. Toggle down the');
out.push('; stack to see how far the silhouettes drift apart: where two mods agree, a');
out.push('; fix written for one of them can be reused for the other.');
out.push(';');
out.push('; Set a layer to Difference mode against the one below to see the drift');
out.push('; directly - black means the two are the same pixel.');
out.push(';');
out.push('; No vanilla layer: RimWorld ships no loose body textures, they live inside');
out.push('; the engine\'s asset bundles.');
out.push('');
out.push('(define (tb-one v) (if (pair? v) (car v) v))');
out.push('');
out.push('(define (tb-exists? file)');
out.push('  (let ((r (file-exists? file)))');
out.push('    (cond ((pair? r) (= (car r) TRUE))');
out.push('          ((number? r) (= r TRUE))');
out.push('          (else r))))');
out.push('');
out.push('(define (tb-add image file name visible)');
out.push('  (if (tb-exists? file)');
out.push('      (let ((layer (tb-one (gimp-file-load-layer RUN-NONINTERACTIVE image file))))');
out.push('        (gimp-image-insert-layer image layer 0 0)');
out.push('        (gimp-item-set-name layer name)');
out.push('        (gimp-item-set-visible layer visible)');
out.push('        layer)');
out.push('      #f))');
out.push('');
out.push('; body facing -> the list of (label . file), deepest layer first.');
out.push('(define tb-table');
out.push('  (list');
for (const row of rows) {
    out.push(`    (list "${row.body}" "${row.facing}"`);
    for (const layer of row.layers) {
        out.push(`      (cons "${esc(layer.label)}" "${esc(layer.file)}")`);
    }
    out.push('    )');
}
out.push('  ))');
out.push('');
out.push('(define (tb-entry body facing)');
out.push('  (let loop ((rows tb-table))');
out.push('    (cond ((null? rows) #f)');
out.push('          ((and (string=? (car (car rows)) body)');
out.push('                (string=? (cadr (car rows)) facing))');
out.push('           (cddr (car rows)))');
out.push('          (else (loop (cdr rows))))))');
out.push('');
out.push('(define (tb-build body facing)');
out.push('  (let ((entry (tb-entry body facing)))');
out.push('    (if (not entry)');
out.push('        (begin (gimp-message "no body texture for that combination") #f)');
out.push('        (let ((image (tb-one (gimp-image-new 512 512 RGB)))');
out.push('              (first TRUE))');
out.push('          (for-each');
out.push('            (lambda (pair)');
out.push('              (tb-add image (cdr pair) (car pair) first)');
out.push('              (set! first FALSE))');
out.push('            entry)');
out.push('          image))))');
out.push('');
out.push('(define (tb-open body facing)');
out.push('  (let ((image (tb-build body facing)))');
out.push('    (if image (begin (gimp-display-new image) (gimp-displays-flush)))');
out.push('    image))');
out.push('');
out.push('(define (tb-open-body body)');
out.push('  (for-each (lambda (f) (tb-open body f)) (list "south" "north" "east")))');
out.push('');

fs.writeFileSync(OUT, out.join('\n'));
console.log(`wrote ${path.relative(ROOT, OUT)}: ${mods.length} mods, ` +
    `${rows.length} body/facing combinations, ` +
    `${rows.reduce((n, r) => n + r.layers.length, 0)} layers in all`);
